create or replace function public.save_sales_invoice(
  p_invoice_id uuid,
  p_shop_id uuid,
  p_invoice_date date,
  p_due_date date,
  p_delivery_date date,
  p_currency text,
  p_discount_amount numeric,
  p_tax_rate numeric,
  p_notes text,
  p_items jsonb
)
returns uuid
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_invoice_id uuid;
  v_current_status public.sales_invoice_status;
  v_item jsonb;
  v_product_id uuid;
  v_product_name text;
  v_sku text;
  v_pack_size text;
  v_product_currency text;
  v_quantity numeric(12,3);
  v_unit_price numeric(14,2);
  v_line_total numeric(14,2);
  v_subtotal numeric(14,2) := 0;
  v_discount numeric(14,2) := round(greatest(coalesce(p_discount_amount, 0), 0), 2);
  v_tax_rate numeric(6,3) := round(greatest(coalesce(p_tax_rate, 0), 0), 3);
  v_taxable numeric(14,2);
  v_tax_amount numeric(14,2);
  v_total numeric(14,2);
  v_sort integer := 0;
begin
  if not public.is_admin() then
    raise exception 'Administrator access is required.';
  end if;

  if p_shop_id is null or not exists (
    select 1 from public.shops where id = p_shop_id and active = true
  ) then
    raise exception 'Select an active shop.';
  end if;

  if p_invoice_date is null or p_due_date is null or p_due_date < p_invoice_date then
    raise exception 'The due date must be on or after the invoice date.';
  end if;

  if p_delivery_date is not null and p_delivery_date < p_invoice_date then
    raise exception 'The delivery date must be on or after the invoice date.';
  end if;

  if p_currency not in ('EUR', 'LKR') then
    raise exception 'Unsupported invoice currency.';
  end if;

  if v_tax_rate > 100 then
    raise exception 'Tax rate cannot be greater than 100 percent.';
  end if;

  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Add at least one product.';
  end if;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_product_id := nullif(v_item->>'product_id', '')::uuid;
    v_quantity := round(coalesce(nullif(v_item->>'quantity', '')::numeric, 0), 3);
    v_unit_price := round(coalesce(nullif(v_item->>'unit_price', '')::numeric, 0), 2);

    if v_product_id is null then
      raise exception 'Every line must have a product.';
    end if;

    select name, sku, pack_size, currency
      into v_product_name, v_sku, v_pack_size, v_product_currency
    from public.products
    where id = v_product_id;

    if not found then
      raise exception 'A selected product no longer exists.';
    end if;

    if v_product_currency <> p_currency then
      raise exception 'All products must use the invoice currency.';
    end if;

    if v_quantity <= 0 then
      raise exception 'Product quantity must be greater than zero.';
    end if;

    if v_unit_price < 0 then
      raise exception 'Unit price cannot be negative.';
    end if;

    v_line_total := round(v_quantity * v_unit_price, 2);
    v_subtotal := v_subtotal + v_line_total;
  end loop;

  v_subtotal := round(v_subtotal, 2);
  if v_discount > v_subtotal then
    raise exception 'Discount cannot be greater than the subtotal.';
  end if;

  v_taxable := round(v_subtotal - v_discount, 2);
  v_tax_amount := round(v_taxable * v_tax_rate / 100, 2);
  v_total := round(v_taxable + v_tax_amount, 2);

  if p_invoice_id is null then
    insert into public.sales_invoices (
      shop_id,
      invoice_date,
      due_date,
      delivery_date,
      currency,
      subtotal,
      discount_amount,
      tax_rate,
      tax_amount,
      total_amount,
      paid_amount,
      balance_amount,
      status,
      delivery_status,
      notes,
      created_by
    )
    values (
      p_shop_id,
      p_invoice_date,
      p_due_date,
      p_delivery_date,
      p_currency,
      v_subtotal,
      v_discount,
      v_tax_rate,
      v_tax_amount,
      v_total,
      0,
      v_total,
      'draft',
      'pending',
      nullif(trim(coalesce(p_notes, '')), ''),
      auth.uid()
    )
    returning id into v_invoice_id;
  else
    select status into v_current_status
    from public.sales_invoices
    where id = p_invoice_id
    for update;

    if not found then
      raise exception 'Invoice not found.';
    end if;

    if v_current_status <> 'draft' then
      raise exception 'Only draft invoices can be edited.';
    end if;

    update public.sales_invoices
    set shop_id = p_shop_id,
        invoice_date = p_invoice_date,
        due_date = p_due_date,
        delivery_date = p_delivery_date,
        currency = p_currency,
        subtotal = v_subtotal,
        discount_amount = v_discount,
        tax_rate = v_tax_rate,
        tax_amount = v_tax_amount,
        total_amount = v_total,
        paid_amount = 0,
        balance_amount = v_total,
        notes = nullif(trim(coalesce(p_notes, '')), '')
    where id = p_invoice_id;

    delete from public.sales_invoice_items where invoice_id = p_invoice_id;
    v_invoice_id := p_invoice_id;
  end if;

  v_sort := 0;
  for v_item in select value from jsonb_array_elements(p_items)
  loop
    v_product_id := nullif(v_item->>'product_id', '')::uuid;
    v_quantity := round(coalesce(nullif(v_item->>'quantity', '')::numeric, 0), 3);
    v_unit_price := round(coalesce(nullif(v_item->>'unit_price', '')::numeric, 0), 2);

    select name, sku, pack_size
      into v_product_name, v_sku, v_pack_size
    from public.products
    where id = v_product_id;

    v_line_total := round(v_quantity * v_unit_price, 2);

    insert into public.sales_invoice_items (
      invoice_id,
      product_id,
      product_name,
      sku,
      pack_size,
      quantity,
      unit_price,
      line_total,
      sort_order
    )
    values (
      v_invoice_id,
      v_product_id,
      v_product_name,
      v_sku,
      v_pack_size,
      v_quantity,
      v_unit_price,
      v_line_total,
      v_sort
    );

    v_sort := v_sort + 1;
  end loop;

  return v_invoice_id;
end;
$$;

create or replace function public.validate_sales_invoice_payment()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_total numeric(14,2);
  v_paid numeric(14,2);
  v_status public.sales_invoice_status;
  v_existing numeric(14,2) := 0;
begin
  if not public.is_admin() then
    raise exception 'Administrator access is required.';
  end if;

  select total_amount, paid_amount, status
    into v_total, v_paid, v_status
  from public.sales_invoices
  where id = new.invoice_id
  for update;

  if not found then
    raise exception 'Invoice not found.';
  end if;

  if v_status in ('draft', 'cancelled') then
    raise exception 'Payments cannot be added to this invoice.';
  end if;

  if tg_op = 'UPDATE' then
    v_existing := old.amount;
  end if;

  if new.amount <= 0 then
    raise exception 'Payment amount must be greater than zero.';
  end if;

  if (v_paid - v_existing + new.amount) > (v_total + 0.01) then
    raise exception 'Payment is greater than the outstanding balance.';
  end if;

  return new;
end;
$$;

create or replace function public.recalculate_sales_invoice_after_payment()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_invoice_id uuid;
  v_paid numeric(14,2);
  v_total numeric(14,2);
  v_due date;
  v_current public.sales_invoice_status;
  v_status public.sales_invoice_status;
begin
  if tg_op = 'DELETE' then
    v_invoice_id := old.invoice_id;
  else
    v_invoice_id := new.invoice_id;
  end if;

  select total_amount, due_date, status
    into v_total, v_due, v_current
  from public.sales_invoices
  where id = v_invoice_id
  for update;

  select coalesce(sum(amount), 0)
    into v_paid
  from public.sales_invoice_payments
  where invoice_id = v_invoice_id;

  v_paid := round(v_paid, 2);

  if v_current = 'cancelled' then
    v_status := 'cancelled';
  elsif v_paid >= v_total - 0.01 then
    v_status := 'paid';
  elsif v_due < current_date then
    v_status := 'overdue';
  elsif v_paid > 0 then
    v_status := 'partially_paid';
  else
    v_status := 'sent';
  end if;

  update public.sales_invoices
  set paid_amount = v_paid,
      balance_amount = greatest(round(v_total - v_paid, 2), 0),
      status = v_status
  where id = v_invoice_id;

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

