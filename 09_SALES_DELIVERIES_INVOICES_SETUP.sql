create or replace function public.refresh_sales_invoice_statuses()
returns integer
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_count integer := 0;
begin
  if not public.is_admin() then
    raise exception 'Administrator access is required.';
  end if;

  update public.sales_invoices
  set status = case
    when paid_amount >= total_amount - 0.01 then 'paid'::public.sales_invoice_status
    when due_date < current_date and balance_amount > 0 then 'overdue'::public.sales_invoice_status
    when paid_amount > 0 then 'partially_paid'::public.sales_invoice_status
    else 'sent'::public.sales_invoice_status
  end
  where status not in ('draft', 'cancelled')
    and status is distinct from case
      when paid_amount >= total_amount - 0.01 then 'paid'::public.sales_invoice_status
      when due_date < current_date and balance_amount > 0 then 'overdue'::public.sales_invoice_status
      when paid_amount > 0 then 'partially_paid'::public.sales_invoice_status
      else 'sent'::public.sales_invoice_status
    end;

  get diagnostics v_count = row_count;
  return v_count;
end;
$$;

