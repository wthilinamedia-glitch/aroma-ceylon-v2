create table if not exists public.sales_invoices (
  id uuid primary key default gen_random_uuid(),
  invoice_number bigint generated by default as identity unique,
  invoice_code text generated always as (
    'INV-' || lpad(invoice_number::text, 6, '0')
  ) stored unique,
  shop_id uuid not null references public.shops(id) on delete restrict,
  invoice_date date not null default current_date,
  due_date date not null default current_date,
  delivery_date date,
  currency text not null default 'EUR' check (currency in ('EUR', 'LKR')),
  subtotal numeric(14,2) not null default 0 check (subtotal >= 0),
  discount_amount numeric(14,2) not null default 0 check (discount_amount >= 0),
  tax_rate numeric(6,3) not null default 0 check (tax_rate >= 0 and tax_rate <= 100),
  tax_amount numeric(14,2) not null default 0 check (tax_amount >= 0),
  total_amount numeric(14,2) not null default 0 check (total_amount >= 0),
  paid_amount numeric(14,2) not null default 0 check (paid_amount >= 0),
  balance_amount numeric(14,2) not null default 0 check (balance_amount >= 0),
  status public.sales_invoice_status not null default 'draft',
  delivery_status public.sales_delivery_status not null default 'pending',
  notes text,
  invoice_pdf_path text,
  delivery_pdf_path text,
  created_by uuid not null references public.profiles(id) on delete restrict,
  sent_at timestamptz,
  delivered_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (due_date >= invoice_date),
  check (delivery_date is null or delivery_date >= invoice_date),
  check (discount_amount <= subtotal),
  check (paid_amount <= total_amount + 0.01),
  check (balance_amount <= total_amount + 0.01)
);

create table if not exists public.sales_invoice_items (
  id uuid primary key default gen_random_uuid(),
  invoice_id uuid not null references public.sales_invoices(id) on delete cascade,
  product_id uuid references public.products(id) on delete restrict,
  product_name text not null,
  sku text not null,
  pack_size text,
  quantity numeric(12,3) not null check (quantity > 0),
  unit_price numeric(14,2) not null check (unit_price >= 0),
  line_total numeric(14,2) not null check (line_total >= 0),
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.sales_invoice_payments (
  id uuid primary key default gen_random_uuid(),
  invoice_id uuid not null references public.sales_invoices(id) on delete cascade,
  payment_date date not null default current_date,
  amount numeric(14,2) not null check (amount > 0),
  payment_method text not null default 'Bank transfer'
    check (payment_method in ('Cash', 'Bank transfer', 'Card', 'Other')),
  reference text,
  notes text,
  created_by uuid not null references public.profiles(id) on delete restrict,
  created_at timestamptz not null default now()
);

